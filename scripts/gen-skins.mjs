// Builds generator/assets/skins.css from the skin sources of the private monorepo (colour tokens, radius, system font stack only).
//   node scripts/gen-skins.mjs /workspace/adesign/ui8kit/xgen/runtimes/core/assets/styles   (also writes generator/assets/skins.json)
// Kept per skin: the 19 shadcn colour tokens + chart-1..5 + sidebar tokens, --radius snapped to the 8px step, a system serif/mono
// stack when the skin's font is a serif/mono face. Dropped: web fonts (no external requests), shadows, tracking, spacing.
import { readFileSync, writeFileSync } from "node:fs";
import { rgb, ratio, ratioRgb, mix, nudge, toHsl } from "./colors.mjs";
const dir = process.argv[2];
if (!dir) throw new Error("usage: gen-skins.mjs <monorepo styles dir>");
const meta = JSON.parse(readFileSync(`${dir}/skins/skins.json`, "utf8"));
const names = [...readFileSync(`${dir}/skins.css`, "utf8").matchAll(/skins\/([\w-]+)\.css/g)].map((m) => m[1]).filter((n) => n !== "base" && n !== "default");
const COLOR = /^(background|foreground|card|card-foreground|popover|popover-foreground|primary|primary-foreground|secondary|secondary-foreground|muted|muted-foreground|accent|accent-foreground|destructive|border|input|ring|chart-[1-5]|sidebar[\w-]*)$/;
const short = (v) => v.replace(/(\d+\.\d+)/g, (n) => String(+(+n).toFixed(1)));
const snap = (rem) => { const px = Math.round((rem * 16) / 8) * 8; return px === 0 ? "0px" : px / 16 + "rem"; };
const take = (src) => {
  const o = {};
  for (const m of src.matchAll(/^\s*--([\w-]+):\s*([^;]+);/gm)) if (COLOR.test(m[1])) o[m[1]] = short(m[2].trim()); else if (m[1] === "radius" || m[1] === "font-sans") o[m[1]] = m[2].trim();
  return o;
};
let out = `/* Skins: <html data-skin="NAME">, light and dark twins (.dark). Generated by scripts/gen-skins.mjs from the ui8kit skin sources
   (colour tokens only; 14 tweakcn presets, Apache-2.0, see NOTICE.md, plus "sky"). The default skin is theme.css (shadcn neutral): no rule here.
   Radius snapped to the 8px step, system fonts only, no shadows or gradients. Contrast fixes live in site.src.css. */\n`;
const list = [], all = {}; // all[name] = {light, dark} resolved colour tokens (skin over theme.css)
const themeCss = readFileSync(new URL("../generator/assets/styles/theme.css", import.meta.url), "utf8");
const siteCss = readFileSync(new URL("../generator/assets/site.src.css", import.meta.url), "utf8");
const tokOf = (re) => Object.fromEntries([...siteCss.match(re)[1].matchAll(/--(tok-[\w-]+):\s*(#[0-9a-f]{6})/g)].map((m) => [m[1], m[2]]));
const tok = { light: tokOf(/:root\s*\{\s*(--tok-[^}]*)\}/), dark: tokOf(/\.dark, \[data-theme="dark"\]\)\s*\{\s*(--tok-[^}]*)\}/) };
for (const n of names) {
  const src = readFileSync(`${dir}/skins/${n}.css`, "utf8");
  const i = src.search(/^[^\n*]*\.dark[^\n]*\{/m);
  const j = src.search(/^\[data-skin="[\w-]+"\] \.shadow/m);
  const l = take(src.slice(0, i)), d = take(src.slice(i, j < 0 ? undefined : j));
  const fam = l["font-sans"] ?? "";
  const font = /serif/.test(fam) && !/sans/.test(fam) ? "ui-serif, Georgia, Cambria, serif" : /monospace/.test(fam) ? "ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" : null;
  const emit = (sel, o, extra) => {
    const body = Object.entries(o).filter(([k]) => k !== "radius" && k !== "font-sans").map(([k, v]) => `--${k}:${v}`);
    if (extra) body.push(...extra);
    return `${sel}{${body.join(";")}}\n`;
  };
  const extra = [];
  if (l.radius) extra.push(`--radius:${snap(parseFloat(l.radius))}`);
  if (font) extra.push(`--font-sans:${font}`);
  out += emit(`:root[data-skin="${n}"]`, l, extra) + emit(`:root[data-skin="${n}"]:is(.dark,[data-theme="dark"])`, d);
  all[n] = { light: l, dark: d };
  list.push({ id: n, label: meta[n]?.label ?? n });
}
// ---- site overrides (contrast fixes, token level, generated): beat the skin rules with html:root[...]; the kit's skins are untouched
out += "/* site overrides: AA contrast fixes per skin and mode (syntax tokens, white text on destructive); lightness moved only, hue kept */\n";
const fixes = [];
for (const n of names) for (const mode of ["light", "dark"]) {
  const dark = mode === "dark", v = all[n][mode], decl = [];
  const surf = ["card", "muted", "background"].map((k) => v[k]);
  for (const [k, c0] of Object.entries(tok[mode])) {
    if (surf.every((b) => ratio(c0, b) >= 4.5)) continue;
    const c = nudge(c0, dark ? 1 : -1, (x) => surf.every((b) => ratioRgb(x, rgb(b)) >= 4.6)) ?? (dark ? "#ffffff" : "#000000");
    decl.push(`--${k}:${c}`); fixes.push(`${n} ${mode} ${k} ${c0}->${c}`);
  }
  const white = (x) => ratioRgb([1, 1, 1], dark ? mix(x, v.background, 0.6) : x);
  const dst = v.destructive ?? (dark ? "hsl(0 62.8% 30.6%)" : "hsl(0 72% 47%)");
  if (white(rgb(dst)) < 4.5) { let c = nudge(dst, -1, (x) => white(x) >= 4.6);
    const dfl = dark ? "hsl(0 62.8% 30.6%)" : "hsl(0 72% 47%)"; // site default when the skin's destructive is not red-ish enough to darken (neutral or pastel)
    if (!c || toHsl(rgb(dst))[1] < 40 || Math.abs(toHsl(rgb(c))[2] - toHsl(rgb(dst))[2]) > 25) c = dfl;
    decl.push(`--destructive:${c}`); fixes.push(`${n} ${mode} destructive ${dst}->${c}`); }
  if (decl.length) out += `html:root[data-skin="${n}"]${dark ? ":is(.dark,[data-theme=\"dark\"])" : ":not(.dark,[data-theme=\"dark\"])"}{${decl.join(";")}}\n`;
}
console.error(fixes.join("\n"));
writeFileSync(new URL("../generator/assets/skins.css", import.meta.url), out);
writeFileSync(new URL("../generator/assets/skins.json", import.meta.url), JSON.stringify(list, null, 1) + "\n");
console.log(names.length, "skins,", out.length, "bytes");
